#!/usr/bin/env python3
"""Independent re-verification of every headline number the live site publishes.

Purpose
-------
The published dashboard (index.html, pages/*.html) is generated by scripts/build_site.py from
data/derived/*.json. Those JSON files are in turn produced by the project's own analysis scripts.
A number can therefore be internally consistent and still be wrong, so this module re-derives each
CLV-relevant headline directly from the committed extracts in data/derived/*.csv.gz, using its own
code paths (no imports from scripts/ or pipeline/).

Each check records
  * `published`  - the value as it appears in the committed JSON the site renders;
  * `recomputed` - the value this independent code computes;
  * `status`     - agree | mismatch | offical-only | unverified | written-never-verified;
  * `source`     - an absolute, official or primary URL the reader can open to check the claim.

A check is only ever marked `agree` when both numbers are finite and within tolerance. Nothing is
filled in by hand: a value that cannot be recomputed is recorded as `unverified` with a blank value.
"""
