#!/usr/bin/env python3
"""Build the signal/staking-split leaderboard.

Input:  origination/site_data/leaderboard.csv (flat-stake backtest ledger,
        generated by origination/scripts; includes luck controls).
        data/strategies.json (staking-plan descriptions).
Output: price-desk/data/leaderboard_split.json

Why the split: ranking strategies on realised returns under a staking plan
lets a lucky staking run mask a bad signal. This board therefore publishes
two blocks and ranks on the SIGNAL block only:

  signal block  - flat-stake performance (no staking choices), price-skill
                  (Brier vs market where published), and luck controls
                  (permutation p, deflated Sharpe, season-block CI).
  staking block - the staking plan each strategy declares, and the realised
                  plan-level outcome. Realised plan outcomes require a live
                  bankroll ledger which does not exist yet, so those cells
                  are BLANK with status "blank-missing" (never inferred).

Nothing here is re-derived by hand: every signal number is copied from the
named CSV; every blank is blank because the source is blank or absent.
"""
import csv
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "price-desk", "data")

SIGNAL_FIELDS = [
    "n_tickets", "n_graded", "pushes", "win_rate", "avg_odds_dec", "avg_fair_prob",
    "roi", "units", "roi_ci95", "roi_ci95_season_block", "perm_p",
    "null_roi_mean", "null_roi_sd", "sharpe_per_bet", "deflated_sharpe",
    "seasons_qualified", "seasons_positive", "roi_first_half", "roi_second_half",
    "brier_model", "brier_market", "model_edge_vs_fair",
]

STAKING_PLANS = {
    # From data/strategies.json descriptions (method-level, not realised).
}


def load_staking_plans():
    try:
        with open(os.path.join(ROOT, "data", "strategies.json")) as f:
            d = json.load(f)
    except OSError:
        return
    rows = d.get("rows", d if isinstance(d, list) else [])
    for r in rows:
        name = r.get("name") or r.get("id") or ""
        plan = r.get("staking") or ""
        if name and plan:
            STAKING_PLANS[name] = plan


def f(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def main():
    load_staking_plans()
    with open(os.path.join(ROOT, "origination", "site_data", "leaderboard.csv")) as f_:
        rows = list(csv.DictReader(f_))

    signal_rows = []
    for r in rows:
        if r.get("family") == "Control":
            continue  # controls are integrity demonstrations, not entrants
        sig = {k: r.get(k, "") for k in SIGNAL_FIELDS if r.get(k, "") != ""}
        sig["strategy"] = r["strategy"]
        sig["family"] = r.get("family", "")
        sig["rule"] = r.get("rule", "")
        sig["tier"] = r.get("tier", "")
        sig["tier_reason"] = r.get("tier_reason", "")
        sig["price_basis"] = "flat stake at closing price (avg_odds_dec); no staking choices in this block"
        signal_rows.append(sig)

    # Signal ranking: luck-adjusted quality first (deflated Sharpe), then
    # permutation p ascending. A row can only be promoted past review when
    # its tier allows it; all current tiers are NEEDS_REVIEW or worse.
    signal_rows.sort(key=lambda s: (-(f(s.get("deflated_sharpe")) or 0.0),
                                    f(s.get("perm_p")) if f(s.get("perm_p")) is not None else 1.0))
    for i, s in enumerate(signal_rows, 1):
        s["signal_rank"] = i

    staking_rows = []
    for r in rows:
        if r.get("family") == "Control":
            continue
        staking_rows.append({
            "strategy": r["strategy"],
            "declared_staking_plan": STAKING_PLANS.get(r["strategy"], ""),
            "declared_staking_plan_status": "ours-reproducible (data/strategies.json)" if STAKING_PLANS.get(r["strategy"]) else "blank-missing (no staking plan declared)",
            "realised_plan_roi": "",
            "realised_plan_roi_status": "blank-missing (no live bankroll ledger exists; cannot be inferred)",
            "max_drawdown": "",
            "max_drawdown_status": "blank-missing (no live bankroll ledger exists; cannot be inferred)",
            "bankroll_series": "",
            "bankroll_series_status": "blank-missing (no live bankroll ledger exists; cannot be inferred)",
        })

    controls = []
    for r in rows:
        if r.get("family") == "Control":
            controls.append({
                "strategy": r["strategy"],
                "rule": r.get("rule", ""),
                "roi": r.get("roi", ""),
                "tier": r.get("tier", ""),
                "tier_reason": r.get("tier_reason", ""),
                "purpose": "integrity demonstration: shows that returns without integrity gates can look spectacular; this row is never eligible for ranking or rewards",
            })

    out = {
        "meta": {
            "title": "Leaderboard - signal block separated from staking block",
            "generated_from": [
                "origination/site_data/leaderboard.csv (flat-stake backtest ledger + luck controls)",
                "data/strategies.json (declared staking plans)",
            ],
            "ranking_rule": "signal_rank is computed from the signal block only (deflated Sharpe desc, permutation p asc). Staking outcomes can never raise or lower a strategy's rank. A lucky staking run cannot mask a bad signal.",
            "status_note": "No strategy currently passes the validation gates: all entrants are tier NEEDS_REVIEW or REJECTED in the source ledger, reward_points are 0 across the board, and the rewards pool is unfunded (flagged). This board is a research competition, not a funded one.",
            "generated_on": "2026-11-14",
        },
        "signal_block": signal_rows,
        "staking_block": staking_rows,
        "controls": controls,
    }
    with open(os.path.join(OUT, "leaderboard_split.json"), "w") as f_:
        json.dump(out, f_, indent=1)
    print(f"signal rows: {len(signal_rows)}, staking rows: {len(staking_rows)}, controls: {len(controls)}")


if __name__ == "__main__":
    main()
